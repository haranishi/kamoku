/**
 * アイコンのSVGを作る。既定は飾り（aria-hidden）。label を渡すと、読み上げる画像になる。
 * 例: icon('check', { label: 'OK' })
 * @param {string} name ICON_NAMES のどれか
 * @param {{ size?: number, label?: string, className?: string }} [opts]
 * @returns {SVGSVGElement}
 */
export function icon(name, opts = {}) {
  const size = opts.size || 20;
  const attrs = {
    class: ['icon', opts.className],
    width: size,
    height: size,
    viewBox: '0 0 20 20',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': 1.75,
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    focusable: 'false',
  };
  if (opts.label) {
    attrs.role = 'img';
    attrs['aria-label'] = opts.label;
  } else {
    attrs['aria-hidden'] = 'true';
  }
  const paths = PATHS[name] || PATHS.info;
  return s('svg', attrs, paths.map((d) => s('path', { d })));
}
